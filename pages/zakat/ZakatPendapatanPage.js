const { expect } = require('@playwright/test');

class ZakatPendapatanPage {

    constructor(page) {

        this.page = page;


        // =====================================================
        // KALKULATOR DAN URUSAN ZAKAT PAGE
        // =====================================================

        this.zakatPendapatanCalculateButton =
            page.getByRole('link', {
                name: 'Kira Sekarang'
            }).first();


        // =====================================================
        // ZAKAT PENDAPATAN PAGE
        // =====================================================

        this.zakatPendapatanHeading =
            page.getByText(
                'Zakat Pendapatan',
                {
                    exact: true
                }
            );

        this.openCalculatorButton =
            page.getByRole('button', {
                name: 'Buka Kalkulator'
            });

        this.addToCartButton =
            page.getByRole('button', {
                name: /Masuk Troli/
            });


        // =====================================================
        // PAYMENT CART
        // =====================================================

        this.paymentCartHeading =
            page.getByText(
                'Bakul Bayaran',
                {
                    exact: true
                }
            );

        this.emptyCartMessage =
            page.getByText(
                'Rekod tidak ditemui. Sila klik Masuk Troli untuk tambah item.',
                {
                    exact: true
                }
            );

        this.payButton =
            page.getByRole('button', {
                name: /^Bayar/
            });


        // =====================================================
        // ZAKAT PENDAPATAN CALCULATOR
        // =====================================================

        this.calculatorHeading =
            page.getByText(
                'Kalkulator Zakat Pendapatan',
                {
                    exact: true
                }
            );

        this.monthlyIncomeOption =
            page.getByText(
                'Bulanan',
                {
                    exact: true
                }
            ).first();

        this.annualIncomeOption =
            page.getByText(
                'Tahunan',
                {
                    exact: true
                }
            ).first();

        this.monthlyIncomeLabel =
            page.getByText(
                'Pendapatan Bulanan',
                {
                    exact: true
                }
            );

        this.bonusLabel =
            page.getByText(
                'Bonus',
                {
                    exact: true
                }
            );

        this.otherIncomeLabel =
            page.getByText(
                'Pendapatan Lain',
                {
                    exact: true
                }
            );

        this.totalIncomeLabel =
            page.getByText(
                'Jumlah Pendapatan',
                {
                    exact: true
                }
            );

        this.nextButton =
            page.getByRole('button', {
                name: /Seterusnya/
            });


        // =====================================================
        // CALCULATOR STEP 1 - MONTHLY INCOME
        // =====================================================

        /*
         * Generated by Playwright Codegen.
         *
         * NOTE:
         * This appears to be a generated Vaadin ID.
         * Keep it isolated here so it can easily be replaced
         * later with a semantic locator.
         */

        this.monthlyIncomeField =
            page.locator(
                '#input-vaadin-big-decimal-field-40'
            );

        this.bonusField =
            page.getByRole(
                'textbox',
                {
                    name: 'Bonus'
                }
            );

        this.otherIncomeField =
            page.getByRole(
                'textbox',
                {
                    name: 'Pendapatan Lain'
                }
            );


        // =====================================================
        // CALCULATOR STEP 1 - ANNUAL INCOME MODE
        // =====================================================

        /*
         * Generated by Playwright Codegen.
         *
         * NOTE:
         * This locator depends on CSS classes.
         * Replace it later if Tahunan receives a stable
         * accessible role/name.
         */

        this.annualModeButton =
            page.locator(
                '.flex-1.gap-xs.items-center.justify-center.p-s.rounded-l.pointer.gray-card-bg'
            );

        this.annualIncomeField =
            page.getByRole(
                'textbox',
                {
                    name: 'Pendapatan Tahunan'
                }
            );


        // =====================================================
        // CALCULATOR STEP 2 - EXPENSE INFORMATION
        // =====================================================

        /*
         * We previously expected the page to contain the exact
         * heading "Maklumat Perbelanjaan".
         *
         * Because this heading was not consistently found,
         * the personal expense field is now used as the
         * reliable indicator that Step 2 has loaded.
         */

        this.personalExpenseField =
            page.getByRole(
                'textbox',
                {
                    name: 'Jumlah Perbelanjaan Diri'
                }
            );

            // =====================================================
            // CALCULATOR STEP 2 - SPOUSE INFORMATION
            // =====================================================

            this.spouseCountField =
                page.getByRole(
                    'spinbutton',
                    {
                        name: 'Bilangan Isteri'
                    }
            );
    }


    // =========================================================
    // OPEN DIGITAL MAIPS
    // =========================================================

    async open() {

        await this.page.goto('/');

        await expect(
            this.zakatPendapatanCalculateButton
        ).toBeVisible({
            timeout: 15000
        });

        console.log(
            'Digital MAIPs opened successfully.'
        );
    }


    // =========================================================
    // OPEN ZAKAT PENDAPATAN
    // =========================================================

    async openZakatPendapatan() {

        await expect(
            this.zakatPendapatanCalculateButton
        ).toBeVisible({
            timeout: 15000
        });

        await expect(
            this.zakatPendapatanCalculateButton
        ).toBeEnabled();

        await this.zakatPendapatanCalculateButton.click();

        console.log(
            'Kira Sekarang clicked.'
        );
    }


    // =========================================================
    // VERIFY ZAKAT PENDAPATAN PAGE
    // =========================================================

    async verifyZakatPendapatanPage() {

        await expect(
            this.zakatPendapatanHeading.first()
        ).toBeVisible({
            timeout: 15000
        });

        await expect(
            this.openCalculatorButton
        ).toBeVisible({
            timeout: 15000
        });

        await expect(
            this.addToCartButton
        ).toBeVisible({
            timeout: 15000
        });

        console.log(
            'Zakat Pendapatan page verified successfully.'
        );
    }


    // =========================================================
    // VERIFY DEFAULT STATE
    // =========================================================

    async verifyDefaultState() {

        await expect(
            this.zakatPendapatanHeading.first()
        ).toBeVisible();

        console.log(
            'Zakat Pendapatan section displayed.'
        );


        await expect(
            this.openCalculatorButton
        ).toBeVisible();

        await expect(
            this.openCalculatorButton
        ).toBeEnabled();

        console.log(
            'Buka Kalkulator button is available.'
        );


        await expect(
            this.addToCartButton
        ).toBeVisible();

        console.log(
            'Masuk Troli button displayed.'
        );


        await expect(
            this.paymentCartHeading
        ).toBeVisible();

        console.log(
            'Bakul Bayaran displayed.'
        );


        await expect(
            this.emptyCartMessage
        ).toBeVisible();

        console.log(
            'Payment cart is empty by default.'
        );


        await expect(
            this.payButton
        ).toBeVisible();

        await expect(
            this.payButton
        ).toBeDisabled();

        console.log(
            'Payment button is disabled because cart is empty.'
        );
    }


    // =========================================================
    // OPEN INCOME CALCULATOR
    // =========================================================

    async openIncomeCalculator() {

        await expect(
            this.openCalculatorButton
        ).toBeVisible({
            timeout: 15000
        });

        await expect(
            this.openCalculatorButton
        ).toBeEnabled();

        await this.openCalculatorButton.click();


        await expect(
            this.calculatorHeading
        ).toBeVisible({
            timeout: 15000
        });

        console.log(
            'Kalkulator Zakat Pendapatan opened.'
        );
    }


    // =========================================================
    // VERIFY CALCULATOR STEP 1
    // =========================================================

    async verifyCalculatorStep1() {

        await expect(
            this.calculatorHeading
        ).toBeVisible({
            timeout: 15000
        });

        console.log(
            'Kalkulator Zakat Pendapatan displayed.'
        );


        await expect(
            this.monthlyIncomeOption
        ).toBeVisible();

        console.log(
            'Bulanan option displayed.'
        );


        await expect(
            this.annualIncomeOption
        ).toBeVisible();

        console.log(
            'Tahunan option displayed.'
        );


        await expect(
            this.monthlyIncomeLabel
        ).toBeVisible();

        await expect(
            this.monthlyIncomeField
        ).toBeVisible();

        console.log(
            'Pendapatan Bulanan field displayed.'
        );


        await expect(
            this.bonusLabel
        ).toBeVisible();

        await expect(
            this.bonusField
        ).toBeVisible();

        console.log(
            'Bonus field displayed.'
        );


        await expect(
            this.otherIncomeLabel
        ).toBeVisible();

        await expect(
            this.otherIncomeField
        ).toBeVisible();

        console.log(
            'Pendapatan Lain field displayed.'
        );


        await expect(
            this.totalIncomeLabel
        ).toBeVisible();

        console.log(
            'Jumlah Pendapatan displayed.'
        );


        await expect(
            this.nextButton
        ).toBeVisible();

        await expect(
            this.nextButton
        ).toBeEnabled();

        console.log(
            'Seterusnya button is available.'
        );
    }


    // =========================================================
    // ENTER MONTHLY INCOME
    // =========================================================

    async enterMonthlyIncome(amount) {

        await expect(
            this.monthlyIncomeField
        ).toBeVisible({
            timeout: 15000
        });

        await this.monthlyIncomeField.fill(
            amount.toString()
        );

        console.log(
            `Monthly income entered: RM ${amount}`
        );
    }


    // =========================================================
    // ENTER BONUS
    // =========================================================

    async enterBonus(amount) {

        await expect(
            this.bonusField
        ).toBeVisible({
            timeout: 15000
        });

        await this.bonusField.fill(
            amount.toString()
        );

        console.log(
            `Bonus entered: RM ${amount}`
        );
    }


    // =========================================================
    // ENTER OTHER INCOME
    // =========================================================

    async enterOtherIncome(amount) {

        await expect(
            this.otherIncomeField
        ).toBeVisible({
            timeout: 15000
        });

        await this.otherIncomeField.fill(
            amount.toString()
        );

        console.log(
            `Other income entered: RM ${amount}`
        );
    }


    // =========================================================
    // ENTER MONTHLY INCOME INFORMATION
    // =========================================================

    async enterIncomeInformation(
        monthlyIncome,
        bonus,
        otherIncome
    ) {

        await this.enterMonthlyIncome(
            monthlyIncome
        );

        await this.enterBonus(
            bonus
        );

        await this.enterOtherIncome(
            otherIncome
        );

        console.log(
            'Monthly income information entered successfully.'
        );
    }


    // =========================================================
    // VERIFY MONTHLY INCOME VALUES
    // =========================================================

    async verifyIncomeValues(
        monthlyIncome,
        bonus,
        otherIncome
    ) {

        await expect(
            this.monthlyIncomeField
        ).toHaveValue(
            new RegExp(
                monthlyIncome.toString()
            )
        );

        await expect(
            this.bonusField
        ).toHaveValue(
            new RegExp(
                bonus.toString()
            )
        );

        await expect(
            this.otherIncomeField
        ).toHaveValue(
            new RegExp(
                otherIncome.toString()
            )
        );

        console.log(
            'Monthly income values verified successfully.'
        );
    }


    // =========================================================
    // SELECT ANNUAL MODE
    // =========================================================

    async selectAnnualMode() {

        await expect(
            this.annualModeButton
        ).toBeVisible({
            timeout: 15000
        });

        await this.annualModeButton.click();


        await expect(
            this.annualIncomeField
        ).toBeVisible({
            timeout: 15000
        });

        console.log(
            'Tahunan income mode selected.'
        );
    }


    // =========================================================
    // ENTER ANNUAL INCOME
    // =========================================================

    async enterAnnualIncome(amount) {

        await expect(
            this.annualIncomeField
        ).toBeVisible({
            timeout: 15000
        });

        await this.annualIncomeField.fill(
            amount.toString()
        );

        console.log(
            `Annual income entered: RM ${amount}`
        );
    }


    // =========================================================
    // ENTER ANNUAL INCOME INFORMATION
    // =========================================================

    async enterAnnualIncomeInformation(
        annualIncome,
        bonus,
        otherIncome
    ) {

        await this.enterAnnualIncome(
            annualIncome
        );

        await this.enterBonus(
            bonus
        );

        await this.enterOtherIncome(
            otherIncome
        );

        console.log(
            'Annual income information entered successfully.'
        );
    }


    // =========================================================
    // VERIFY ANNUAL INCOME VALUES
    // =========================================================

    async verifyAnnualIncomeValues(
        annualIncome,
        bonus,
        otherIncome
    ) {

        await expect(
            this.annualIncomeField
        ).toHaveValue(
            new RegExp(
                annualIncome.toString()
            )
        );

        await expect(
            this.bonusField
        ).toHaveValue(
            new RegExp(
                bonus.toString()
            )
        );

        await expect(
            this.otherIncomeField
        ).toHaveValue(
            new RegExp(
                otherIncome.toString()
            )
        );

        console.log(
            'Annual income values verified successfully.'
        );
    }


    // =========================================================
    // CLICK NEXT
    // =========================================================

    async clickNext() {

        await expect(
            this.nextButton
        ).toBeVisible({
            timeout: 15000
        });

        await expect(
            this.nextButton
        ).toBeEnabled();

        await this.nextButton.click();

        console.log(
            'Seterusnya button clicked.'
        );
    }


    // =========================================================
    // VERIFY CALCULATOR STEP 2
    // =========================================================

    async verifyCalculatorStep2() {

        /*
         * Instead of checking the unreliable
         * "Maklumat Perbelanjaan" heading,
         * verify the real expense input.
         */

        await expect(
            this.personalExpenseField
        ).toBeVisible({
            timeout: 15000
        });

        console.log(
            'Expense information step displayed successfully.'
        );
    }


    // =========================================================
    // ENTER PERSONAL EXPENSE
    // =========================================================

    async enterPersonalExpense(amount) {

        await expect(
            this.personalExpenseField
        ).toBeVisible({
            timeout: 15000
        });

        await this.personalExpenseField.fill(
            Number(amount).toFixed(2)
        );

        console.log(
            `Personal expense entered: RM ${Number(amount).toFixed(2)}`
        );
    }


    // =========================================================
    // VERIFY PERSONAL EXPENSE
    // =========================================================

    async verifyPersonalExpense(amount) {

        /*
         * Accept values such as:
         *
         * 1000
         * 1000.00
         * 1,000
         * 1,000.00
         */

        const expectedValue =
            Number(amount).toLocaleString(
                'en-US',
                {
                    minimumFractionDigits: 0,
                    maximumFractionDigits: 2
                }
            );

        const escapedValue =
            expectedValue
                .replace(
                    /,/g,
                    '[,]?'
                )
                .replace(
                    /\./g,
                    '\\.'
                );

        await expect(
            this.personalExpenseField
        ).toHaveValue(
            new RegExp(
                `^${escapedValue}(?:\\.00)?$`
            )
        );

        console.log(
            'Personal expense value verified successfully.'
        );
    }


    // =========================================================
    // ENTER EXPENSE AND CONTINUE
    // =========================================================

    async enterPersonalExpenseAndContinue(amount) {

        await this.verifyCalculatorStep2();

        await this.enterPersonalExpense(
            amount
        );

        await this.verifyPersonalExpense(
            amount
        );

        await this.clickNext();

        console.log(
            'Personal expense submitted successfully.'
        );
    }

    // =========================================================
// ENTER SPOUSE COUNT
// =========================================================

async enterSpouseCount(count) {

    await expect(
        this.spouseCountField
    ).toBeVisible({
        timeout: 15000
    });

    await this.spouseCountField.fill(
        count.toString()
    );

    console.log(
        `Bilangan Isteri entered: ${count}`
    );
}


// =========================================================
// VERIFY SPOUSE COUNT
// =========================================================

async verifySpouseCount(count) {

    await expect(
        this.spouseCountField
    ).toHaveValue(
        count.toString()
    );

    console.log(
        'Bilangan Isteri verified successfully.'
    );
}
}


// =============================================================
// EXPORT PAGE OBJECT
// =============================================================

module.exports = {
    ZakatPendapatanPage
};